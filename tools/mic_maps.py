"""Writes crates/koala-capture/data/mic-maps.json: which microphone each of
an iPhone's audio channels is, for every iPhone an iOS build supports.

usage: python3 -I tools/mic_maps.py BUILD OUT.json [--dtrees DIR]

Needs `ipsw` (https://github.com/blacktop/ipsw) on PATH. Lists the build's
iPhone IPSWs, fetches only their device trees (`ipsw extract --remote
--dtree`, a few hundred KB each) into DIR (default: a temporary directory),
and reads each tree's audio codec node:

- `<code>-mic` properties name the built-in microphones by four-character
  code. The value's lowest byte is the codec input; the channels come in
  input order (checked against the stream on one model; see CHECKED).
- `<code>-mic-swap` properties give a variant board where two microphones
  trade inputs, so those two can trade channels.
- The root node's `compatible` names the board and the model, and
  `product-name` the marketing name.

What each code means is not in the tree. MEANINGS holds it, from listening
to a model's channels (CHECKED).
"""
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

# What each code is, from the iPhone 17 Pro's four channels in trial 22
# (2026-11-19, Koala's docs/guest-pairing.md): imic, smic, fmic and lmic, in
# input order, sounded like the bottom, back, front and bottom microphones.
MEANINGS = {
    "imic": {"id": "bottom-1", "name": "Bottom 1", "place": "bottom edge"},
    "smic": {"id": "back", "name": "Back", "place": "back, by the cameras"},
    "fmic": {"id": "front", "name": "Front", "place": "front, at the earpiece"},
    "lmic": {"id": "bottom-2", "name": "Bottom 2", "place": "bottom edge"},
}
# Models whose channel order was checked against their audio, and how.
CHECKED = {"iPhone18,1": "by ear, trial 22 (2026-11-19)"}


def ipsw(*args):
    return subprocess.run(["ipsw", *args], capture_output=True, text=True, check=True).stdout


def fetch(build, out):
    urls = sorted({u for u in ipsw("download", "ipsw", "--build", build, "--urls").split() if "/iPhone" in u})
    for url in urls:
        ipsw("extract", "--remote", "--dtree", url, "--output", out)
    return len(urls)


def props(node, found):
    """Every (key, value) in a tree from `ipsw dtree --json`, depth first."""
    if isinstance(node, dict):
        for k, v in node.items():
            if isinstance(v, (dict, list)):
                props(v, found)
            else:
                found.append((k, v))
    elif isinstance(node, list):
        for v in node:
            props(v, found)
    return found


def model_of(tree_path):
    tree = json.loads(ipsw("dtree", tree_path, "--json"))
    found = props(tree, [])
    compatible = tree["device-tree"]["compatible"]
    mics = {k[: -len("-mic")]: v for k, v in found if k.endswith("-mic") and isinstance(v, int)}
    swaps = sorted(k[: -len("-mic-swap")] for k, _ in found if k.endswith("-mic-swap"))
    builtin = next((v for k, v in found if k == "builtin-mics"), None)
    if builtin is not None and builtin != len(mics):
        sys.exit(f"{tree_path}: builtin-mics is {builtin}, but {len(mics)} mics are named")
    unknown = set(mics) - set(MEANINGS)
    if unknown:
        sys.exit(f"{tree_path}: codes with no meaning yet: {sorted(unknown)}")
    entry = {
        "name": next(v for k, v in found if k == "product-name"),
        "board": compatible[0],
        "channels": sorted(mics, key=lambda code: mics[code] & 0xFF),
    }
    if swaps:
        entry["swappable"] = swaps
    return compatible[1], entry


def main():
    args = sys.argv[1:]
    dtrees = None
    if "--dtrees" in args:
        at = args.index("--dtrees")
        dtrees = args[at + 1]
        del args[at : at + 2]
    if len(args) != 2:
        sys.exit(__doc__)
    build, out = args
    with tempfile.TemporaryDirectory() as tmp:
        if dtrees is None:
            dtrees = tmp
            print(f"{fetch(build, dtrees)} IPSWs for build {build}")
        models = {}
        for path in sorted(glob.glob(os.path.join(dtrees, "**", "DeviceTree.*.im4p"), recursive=True)):
            model, entry = model_of(path)
            if model in CHECKED:
                entry["checked"] = CHECKED[model]
            models[model] = entry
    orders = [tuple(m["channels"]) for m in models.values()]
    default = max(set(orders), key=orders.count)
    key = lambda m: tuple(int(x) for x in m[len("iPhone"):].split(","))  # noqa: E731
    doc = {
        "about": "Which microphone each of an iPhone's audio channels is. Generated by tools/mic_maps.py; "
        "see it for the sources. `default` is the most common order, for models not listed.",
        "build": build,
        "mics": MEANINGS,
        "default": list(default),
        "models": {m: models[m] for m in sorted(models, key=key)},
    }
    text = json.dumps(doc, indent=2)
    # Lists of codes on one line each.
    text = re.sub(r'\[\s+((?:"\w+",?\s*)+)\]', lambda m: "[" + ", ".join(re.findall(r'"\w+"', m[1])) + "]", text)
    with open(out, "w", newline="\n") as f:
        f.write(text + "\n")
    print(f"{len(models)} models written to {out}")


main()
