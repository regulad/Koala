"""Writes crates/koala/data/third-party-notices.txt: the licences of the
software built into Koala's programs, for the tray's About window.

usage: python -I tools/third_party_notices.py  (from the repository root)

Walks `cargo metadata` for Windows from the `koala` package through normal
dependencies (not build or dev ones, which aren't built in) and collects each
package's licence files, deduplicated: identical texts appear once, and each
package names the ones it ships. C code a crate builds in, which its own
licence files don't cover, is listed in VENDORED.

The file ends with a hash of Cargo.lock (FNV-1a, 64 bits); a test in the
`koala` crate fails when Cargo.lock no longer matches, so the notices are
regenerated whenever the dependencies change.
"""
import json
import os
import subprocess
import sys

TARGET = "x86_64-pc-windows-msvc"
LICENCE_PREFIXES = ("license", "licence", "copying", "copyright", "notice", "unlicense")
# Licence files of C code built into a crate, under its directory.
VENDORED = {"opusic-sys": ["opus/COPYING"]}


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    root = os.getcwd()
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = next(i for i in members if packages[i]["name"] == "koala")
    seen, todo = set(), [start]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    third = sorted((packages[i] for i in seen - members), key=lambda p: (p["name"].lower(), p["version"]))

    texts = {}  # text -> number
    entries = []
    for p in third:
        directory = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(directory) if f.lower().startswith(LICENCE_PREFIXES))
        files = [os.path.join(directory, f) for f in files if os.path.isfile(os.path.join(directory, f))]
        files += [os.path.join(directory, f) for f in VENDORED.get(p["name"], [])]
        refs = []
        for path in files:
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read().replace("\r\n", "\n").lstrip("\ufeff")
            # Trailing spaces off, as the repository's hooks want.
            text = "\n".join(line.rstrip() for line in text.split("\n")).strip("\n")
            number = texts.setdefault(text, len(texts) + 1)
            refs.append(f"[{number}] {os.path.relpath(path, directory).replace(os.sep, '/')}")
        entries.append((p, refs))

    out = [
        "Third-party software in Koala",
        "",
        "Koala's programs are built from the following free software, under the",
        "licences given. Each package's licence files follow, by number, after",
        "the list.",
        "",
    ]
    for p, refs in entries:
        out.append(f"{p['name']} {p['version']}")
        out.append(f"  Licence: {p.get('license') or 'see its files'}")
        if p.get("repository"):
            out.append(f"  Source: {p['repository']}")
        if refs:
            out.append(f"  Files: {', '.join(refs)}")
        elif p["source"] is None:
            out.append("  Used under the AGPL-3.0-or-later, Koala's own licence.")
        out.append("")
    out += ["", "Licence texts", ""]
    for text, number in sorted(texts.items(), key=lambda kv: kv[1]):
        out += [f"[{number}]", "", text, "", ""]
    with open(os.path.join(root, "Cargo.lock"), "rb") as f:
        lock = fnv1a64(f.read())
    out.append(f"Generated by tools/third_party_notices.py from Cargo.lock {lock:016x}.")
    target = os.path.join(root, "crates", "koala", "data", "third-party-notices.txt")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(entries)} packages, {len(texts)} distinct licence texts, written to {target}", file=sys.stderr)


main()
